// Its own palette, as the troll's is: nothing in assets/palette.gpl is a bass.
// Olive on the back down to cream on the belly, the countershading a real one
// has, with the dark band of blotches along the flank that makes a largemouth
// read as one; and one skin ramp for the man, warm against the fish's greens, so
// the parts that are not fish are the first thing the eye separates out. The
// heart and the arm repeat tones under their own letters, as the troll's chest
// does.
