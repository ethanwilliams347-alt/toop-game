inline constexpr int PALETTE_COUNT = static_cast<int>(sizeof(PALETTE) / sizeof(PALETTE[0]));

inline constexpr int FOOT_ROWS = 3;
// The arm is lettered, so every row may hold it.
inline constexpr int ARM_TOP = 0;
// The box is the fish's middle and the legs: 30 columns, centred. species::FISH
// checks it against its own box width.
inline constexpr int BOX_LEFT = 32;
inline constexpr int BOX_RIGHT = W - BOX_LEFT;
// Where the arm turns: the top of the head, where it grows out. species::FISH's
// rig turns the arm about this same point, and says so with a static_assert.
inline constexpr int SHOULDER_X = 60;
inline constexpr int SHOULDER_Y = 22;
// The rows inside the box from which a pixel is leg, and the column the rear leg
// ends before; the rig's hip_row and leg_split, stated here so the checks below
// can read them.
inline constexpr int HIP_ROW = 53;
inline constexpr int LEG_SPLIT = 47;

inline constexpr body_art::Art ART = body_art::with_arm_box(body_art::Art{
    ROWS, W, H, PALETTE, PALETTE_COUNT, "EO", "abcdfg", BOX_LEFT, ARM_TOP, FOOT_ROWS, "pqrs"});

static_assert(body_art::well_formed(ART),
              "fish_art::ROWS has a row of the wrong width or a character with no "
              "PALETTE entry");
static_assert(body_art::count_where(ART, &body_art::Art::is_head) >= 9 &&
                  body_art::count_where(ART, &body_art::Art::is_heart) > 0,
              "the fish needs its whole eye ('E'/'O') and a heart ('a'-'g'), or it "
              "is born dead -- or dies to one arrow in the eye");
static_assert(body_art::count_where(ART, &body_art::Art::is_foot) > 0,
              "the fish has nothing in its FOOT_ROWS inside the box, so it is born "
              "footless and collapses on its first hit");
static_assert(body_art::count_where(ART, &body_art::Art::is_arm) > 0,
              "the fish has no arm letters ('p'-'s'), so it is born armless and "
              "can never cast");
static_assert(body_art::connected<W * H>(ART),
              "some fish pixel is not 8-connected to the heart; it would fall off "
              "as sand the first time the fish is hit anywhere");
static_assert(body_art::stands_on_bottom_row(ART), "the fish art floats: its bottom row is empty");

// The arm touches the rest of the body only at its root. A pixel of it beside
// the head anywhere further out -- the hand against the lip, the forearm along
// the brow -- would hold the arm on after the shoulder was shot through.
constexpr bool arm_hangs_free() {
    for (int y = 0; y < H; ++y)
        for (int x = 0; x < W; ++x) {
            if (!ART.is_arm(x, y)) continue;
            const int sx = x - SHOULDER_X, sy = y - SHOULDER_Y;
            if (sx * sx + sy * sy <= 9) continue;
            for (int dy = -1; dy <= 1; ++dy)
                for (int dx = -1; dx <= 1; ++dx) {
                    const int nx = x + dx, ny = y + dy;
                    if (nx < 0 || nx >= W || ny < 0 || ny >= H) continue;
                    if (ART.is_body(nx, ny) && !ART.is_arm(nx, ny)) return false;
                }
        }
    return true;
}
static_assert(arm_hangs_free(),
              "a fish pixel touches the arm away from the shoulder, so the arm can "
              "no longer be shot off at the shoulder");

// The legs hang from the hips alone: the columns either side of the split are
// empty from the hips down, and the rows above the hips inside the box -- the
// belly -- are where each joins the body.
constexpr bool legs_hang_free() {
    for (int y = HIP_ROW; y < H; ++y)
        if (ART.is_body(LEG_SPLIT - 1, y) || ART.is_body(LEG_SPLIT, y)) return false;
    return true;
}
static_assert(legs_hang_free(),
              "a fish pixel fills the gap between the legs, so neither leg can be "
              "severed at the hip on its own");

inline constexpr int PIXEL_COUNT = body_art::count_where(ART, &body_art::Art::is_body);

