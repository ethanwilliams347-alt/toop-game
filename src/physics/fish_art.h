// The fish's body, one character per pixel and one pixel per world cell, read
// by body_art's rules for the reasons enemy_art.h gives for keeping a body's art
// in src/physics/ at all.
//
// A largemouth bass on a man's legs, nose tilted up, with a man's arm growing out
// of the top of its head: up, over the snout, and down to a hand hanging limp at
// the wrist in front of the mouth -- the anglerfish's lure, if the lure were a
// hand. 94x84, the troll's 70 rows plus a fifth: from the elbow's crown to the
// soles it stands 80 cells against the troll's 66.
//
// Drawn the way the player's owl is rather than the way the troll is: no
// outline, three or four tones a material, and the form carried by where one
// tone meets the next. Generated by tools/fish_art.py from shapes, for the
// troll's reason (troll_art.h); regenerate with `python tools/fish_art.py` and
// paste the rows over ROWS below. The static_asserts at the bottom decide whether
// the result is still a body.
//
// The roles:
//  - 'E' and 'O', the eye, are the HEAD. Four across, so one arrow's bite
//    (radius 2) through the pupil leaves a rim of it: two good shots, as for the
//    troll's two eyes, rather than one lucky one.
//  - 'a' to 'g', the middle of the flank, are the HEART and the root of the
//    severing fill.
//  - 'p' 'q' 'r' 's', the arm, are the ARM by letter (body_art::Art::arm),
//    because no column rule can say which of the pixels above and in front of
//    the head are arm. It joins the head only within a few cells of the
//    shoulder -- checked below -- so a shot through the shoulder takes the whole
//    arm off, and the hand hanging by the lip never fuses to it.
//  - The legs are geometry, as for every body: inside the box's columns from
//    Species::rig.hip_row down. Nothing else of the fish is there -- the fins
//    that hang below the belly are outside the box -- and the two columns either
//    side of the leg split are empty, so a leg hangs from its hip alone.
